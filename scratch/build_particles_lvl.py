"""
Generates LVLang bytecode (.lvl) for a 2D Hardware-Accelerated Particle Fountain Physics Simulator.
RAM Layout (30 Particles):
Particle i (0 <= i < 30):
  RAM[i*4 + 0] = X (0..800)
  RAM[i*4 + 1] = Y (0..600)
  RAM[i*4 + 2] = VX (-10..10)
  RAM[i*4 + 3] = VY (-15..5)
"""

def assemble_particles_lvl():
    bc = []

    # 1. Initialize SDL2 Window (Width=800, Height=600)
    bc.extend([0x01, 0x08, 0x20, 0x03]) # PUSH_IMM16 800
    bc.extend([0x01, 0x08, 0x58, 0x02]) # PUSH_IMM16 600
    bc.extend([0x0E, 0x01, 0x06, 0x01]) # SDL_INIT_WINDOW
    bc.extend([0x01, 0x01])             # POP result

    # 2. Initialize 30 Particles in RAM
    # R0 = i = 0
    bc.extend([0x01, 0x80, 0x01, 0x30])

    # INIT_LOOP (Inst 8 / Byte 16):
    # base_addr = i * 4
    bc.extend([0x01, 0x10, 0x01, 0x84, 0x02, 0x03, 0x01, 0x31])

    # X = 400
    bc.extend([0x01, 0x08, 0x90, 0x01, 0x01, 0x51])

    # INC R1
    bc.extend([0x02, 0x11])
    # Y = 100
    bc.extend([0x01, 0x08, 0x64, 0x00, 0x01, 0x51])

    # INC R1
    bc.extend([0x02, 0x11])
    # VX = (i % 11) - 5
    bc.extend([0x01, 0x10, 0x01, 0x8B, 0x02, 0x05, 0x01, 0x85, 0x02, 0x02, 0x01, 0x51])

    # INC R1
    bc.extend([0x02, 0x11])
    # VY = -12 + (i % 7)
    bc.extend([0x01, 0x80, 0x01, 0x8C, 0x02, 0x02, 0x01, 0x10, 0x01, 0x87, 0x02, 0x05, 0x02, 0x01, 0x01, 0x51])

    # INC R0 (i++)
    bc.extend([0x02, 0x10])
    # if i < 30 -> JMP back to INIT_LOOP
    bc.extend([0x01, 0x10, 0x01, 0x9E, 0x03, 0x04]) # i < 30
    bc.extend([0x0D, 0x01])                         # JZ skip jump
    bc.extend([0x09, 0x21])                         # JMP_REL_BACK 33 instructions back to Inst 8

    # MAIN GAME/SIMULATION LOOP (Inst 43 / Byte 86):

    # 1. Clear Screen (Background R=10, G=15, B=25 - Deep Space)
    bc.extend([0x01, 0x8A, 0x01, 0x8F, 0x01, 0x99, 0x0E, 0x01, 0x06, 0x02])
    bc.extend([0x0E, 0x01, 0x06, 0x03])

    # 2. Physics & Render Loop for 30 Particles:
    # R0 = i = 0
    bc.extend([0x01, 0x80, 0x01, 0x30])

    # PARTICLE_LOOP (Inst 49 / Byte 98):
    # base_addr = i * 4
    bc.extend([0x01, 0x10, 0x01, 0x84, 0x02, 0x03, 0x01, 0x31])

    # Read X, Y, VX, VY
    bc.extend([0x01, 0x41, 0x01, 0x32])
    bc.extend([0x02, 0x11])
    bc.extend([0x01, 0x41, 0x01, 0x33])
    bc.extend([0x02, 0x11])
    bc.extend([0x01, 0x41, 0x01, 0x34])
    bc.extend([0x02, 0x11])
    bc.extend([0x01, 0x41, 0x01, 0x35])

    # --- Physics Update ---
    # Gravity: VY = VY + 1
    bc.extend([0x02, 0x15])

    # Position: X = X + VX, Y = Y + VY
    bc.extend([0x01, 0x12, 0x01, 0x14, 0x02, 0x01, 0x01, 0x32])
    bc.extend([0x01, 0x13, 0x01, 0x15, 0x02, 0x01, 0x01, 0x33])

    # Floor Bounce Check: if Y > 540 -> Y = 540, VY = -(VY * 7 / 10)
    bc.extend([0x01, 0x13, 0x01, 0x08, 0x1C, 0x02, 0x03, 0x03]) # Y > 540 ?
    bc.extend([0x0D, 0x0B]) # JZ skip floor bounce (11 instructions)
    bc.extend([0x01, 0x08, 0x1C, 0x02, 0x01, 0x33]) # Y = 540
    bc.extend([0x01, 0x80, 0x01, 0x15, 0x01, 0x87, 0x02, 0x03, 0x01, 0x8A, 0x02, 0x04, 0x02, 0x02, 0x01, 0x35])

    # Respawn Check: if Y >= 535 -> Reset to fountain
    bc.extend([0x01, 0x13, 0x01, 0x08, 0x17, 0x02, 0x03, 0x03]) # Y > 535 ?
    bc.extend([0x0D, 0x0A]) # JZ skip respawn (10 instructions)
    bc.extend([0x01, 0x08, 0x90, 0x01, 0x01, 0x32]) # X=400
    bc.extend([0x01, 0x08, 0x64, 0x00, 0x01, 0x33]) # Y=100
    bc.extend([0x01, 0x80, 0x01, 0x8C, 0x02, 0x02, 0x01, 0x35]) # VY=-12

    # Save updated physics back to RAM:
    bc.extend([0x01, 0x10, 0x01, 0x84, 0x02, 0x03, 0x01, 0x31])
    bc.extend([0x01, 0x12, 0x01, 0x51, 0x02, 0x11])
    bc.extend([0x01, 0x13, 0x01, 0x51, 0x02, 0x11])
    bc.extend([0x01, 0x14, 0x01, 0x51, 0x02, 0x11])
    bc.extend([0x01, 0x15, 0x01, 0x51])

    # --- Render Particle ---
    # Set Glowing Gold/Cyan Color: R=255, G=(Y % 255), B=150
    bc.extend([0x01, 0x08, 0xFF, 0x00, 0x01, 0x13, 0x01, 0x08, 0x96, 0x00, 0x0E, 0x01, 0x06, 0x02])
    # Draw Rect: X (R2), Y (R3), W=8, H=8
    bc.extend([0x01, 0x12, 0x01, 0x13, 0x01, 0x88, 0x01, 0x88, 0x0E, 0x01, 0x06, 0x04])

    # INC R0 (i++)
    bc.extend([0x02, 0x10])
    # if i < 30 -> JMP back to PARTICLE_LOOP
    bc.extend([0x01, 0x10, 0x01, 0x9E, 0x03, 0x04]) # i < 30
    bc.extend([0x0D, 0x01])                         # JZ skip jump
    bc.extend([0x09, 0x55])                         # JMP_REL_BACK 85 instructions back to PARTICLE_LOOP

    # 3. Flip Frame Buffer & Sleep 16ms (~60 FPS)
    bc.extend([0x0E, 0x01, 0x06, 0x05]) # SDL_PRESENT
    bc.extend([0x01, 0x90, 0x0E, 0x01, 0x07, 0x04]) # TIME_SLEEP_MS 16

    # 4. Check Poll Events (Quit)
    bc.extend([0x0E, 0x01, 0x06, 0x06]) # SDL_POLL_EVENTS
    bc.extend([0x0F, 0x01])             # JNZ to HALT

    # JMP back to MAIN LOOP (Inst 43)
    bc.extend([0x09, 0x64])             # JMP_REL_BACK 100 instructions back to MAIN LOOP

    bc.extend([0x05, 0xFF]) # HALT

    # Format as 01x08 20x03 ... pairs
    formatted_opcodes = []
    for i in range(0, len(bc), 2):
        if i + 1 < len(bc):
            formatted_opcodes.append(f"{bc[i]:02X}x{bc[i+1]:02X}")

    return " ".join(formatted_opcodes)

if __name__ == "__main__":
    bytecode_str = assemble_particles_lvl()
    with open("particles.lvl", "w") as f:
        f.write(bytecode_str + "\n")
    print(f"[+] Successfully compiled particles.lvl ({len(bytecode_str.split()) * 2} bytes)")
